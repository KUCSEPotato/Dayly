import { expect, test } from '@playwright/test'

test('workspace menus and summary arrows open the correct completed-period tab', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: '나만의 회고', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '나만의 세계', exact: true })).toBeVisible()
  await page.getByRole('region', { name: '달성률 요약' }).getByRole('button', { name: '오늘', exact: true }).click()
  await page.getByRole('button', { name: '일간 회고 보기' }).click()
  await expect(page.getByRole('tab', { name: '일간 회고' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('heading', { name: '활동 기록 없음' })).toBeVisible()
  await page.getByRole('button', { name: '나의 하루', exact: true }).click()
  await page.getByRole('region', { name: '달성률 요약' }).getByRole('button', { name: '최근 7일', exact: true }).click()
  await page.getByRole('button', { name: '주간 회고 보기' }).click()
  await expect(page.getByRole('tab', { name: '주간 회고' })).toHaveAttribute('aria-selected', 'true')
})

test('weekly snapshot, previous/next navigation, task lists and monthly graph', async ({ page }, testInfo) => {
  await page.goto('/#retrospectives/weekly')
  await expect(page.getByRole('button', { name: '이전 회고' })).toBeEnabled()
  await page.getByRole('button', { name: '이전 회고' }).click()
  await expect(page.getByText('회고 검증 · 완료', { exact: true })).toBeVisible()
  await expect(page.getByText('회고 검증 · 미완료', { exact: true })).toBeVisible()
  await expect(page.getByRole('progressbar', { name: '고정 회고 달성률' })).toHaveAttribute('aria-valuenow', '50')
  await expect(page.getByRole('region', { name: '고정 회고 요약' })).toContainText('20')
  await page.screenshot({ path: testInfo.outputPath('retrospective-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('retrospective-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: '다음 회고' }).click()
  await expect(page.getByRole('heading', { name: '활동 기록 없음' })).toBeVisible()
  await expect(page.getByRole('button', { name: '다음 회고' })).toBeDisabled()
  await page.getByRole('tab', { name: '월간 회고' }).click()
  await expect(page.getByRole('group', { name: '회고 날짜별 달성률' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('unknown history is distinguished from no activity and failures can be retried', async ({ page }) => {
  await page.goto('/#retrospectives/weekly')
  for (let index = 0; index < 7; index++) {
    await expect(page.getByRole('button', { name: '이전 회고' })).toBeEnabled()
    await page.getByRole('button', { name: '이전 회고' }).click()
  }
  await expect(page.getByText('기록 복원 불가', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '활동 기록 없음' })).not.toBeVisible()
  await page.route('**/api/retrospectives?**', route => route.abort())
  await page.getByRole('tab', { name: '일간 회고' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.unroute('**/api/retrospectives?**')
  await page.getByRole('button', { name: '다시 시도' }).click()
  await expect(page.getByRole('heading', { name: '활동 기록 없음' })).toBeVisible()
})

test('world shares real XP and level, survives reload and fits mobile', async ({ page }, testInfo) => {
  await page.goto('/#world')
  const growth = page.getByRole('region', { name: '성장 상태' })
  await expect(growth).toBeVisible()
  const response = await page.request.get('/api/growth/summary')
  const summary: { total_xp: number; level: number } = await response.json()
  await expect(growth).toContainText(`Lv. ${summary.level}`)
  await expect(growth.locator('.growth-progress strong')).toHaveText(`${summary.total_xp} XP`)
  await expect(page.getByText('FOREST', { exact: true })).toBeVisible()
  await expect(page.getByText('OCEAN', { exact: true })).toBeVisible()
  await expect(page.getByText('COMING SOON · v1.0')).toBeVisible()
  await expect(page.getByRole('heading', { name: '경험치 획득 내역' })).toBeVisible()
  await page.reload()
  await expect(growth.locator('.growth-progress strong')).toHaveText(`${summary.total_xp} XP`)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('world-mobile.png'), fullPage: true })
})
